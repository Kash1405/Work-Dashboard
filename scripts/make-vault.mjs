// Writes src/lib/vault.data.ts for a new dashboard password: an AES-256-GCM encrypted marker
// whose key is derived from the password (PBKDF2, 600k rounds). The password itself is never stored.
// Usage: npm run vault   (you will be asked for the password)
import { webcrypto as crypto } from "node:crypto";
import { writeFileSync } from "node:fs";
import { createInterface } from "node:readline/promises";

const rl = createInterface({ input: process.stdin, output: process.stdout });
const password = await rl.question("New dashboard password: ");
rl.close();
if (!password) process.exit(1);

const iterations = 600000;
const salt = crypto.getRandomValues(new Uint8Array(16));
const iv = crypto.getRandomValues(new Uint8Array(12));
const base = await crypto.subtle.importKey("raw", new TextEncoder().encode(password), "PBKDF2", false, ["deriveKey"]);
const key = await crypto.subtle.deriveKey({ name: "PBKDF2", salt, iterations, hash: "SHA-256" }, base, { name: "AES-GCM", length: 256 }, false, ["encrypt"]);
const data = new Uint8Array(await crypto.subtle.encrypt({ name: "AES-GCM", iv }, key, new TextEncoder().encode(JSON.stringify({ app: "work-dashboard" }))));
const b64 = (bytes) => Buffer.from(bytes).toString("base64");

writeFileSync(new URL("../src/lib/vault.data.ts", import.meta.url), `// Password check for the lock screen (AES-256-GCM, key derived from the dashboard password with PBKDF2).
// Generated by scripts/make-vault.mjs. It cannot be opened without the password.
export const VAULT = {
  iterations: ${iterations},
  salt: "${b64(salt)}",
  iv: "${b64(iv)}",
  data: "${b64(data)}",
};
`);
console.log("Wrote src/lib/vault.data.ts");
